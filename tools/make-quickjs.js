"use strict";
// Script mods' sandbox (docs/MODS.md 2): QuickJS (a small JavaScript engine) in WebAssembly, from the npm packages
// quickjs-emscripten-core + @jitl/quickjs-wasmfile-release-sync (package.json, exact versions) - vendored into src/ so
// that every way the game runs loads the same bytes the same way: node tests, the browser from src/ unbundled
// (STATIC_DIR=src: no bare imports there), the esbuild build (a chunk of its own - mods.js imports it only when a
// modded match starts) and the apps.
//   src/js/vendor/quickjs.js    the JavaScript side as one ES module (the browser flavour; it never fetches anything
//                               itself - mods.js hands it the WebAssembly bytes): {newQuickJSWASMModuleFromVariant,
//                               newVariant, variant}
//   src/js/vendor/quickjs.wasm  the WebAssembly (build.js copies it to public/js/vendor/)
// Run again after changing the packages' version (test/mods-check.js checks the .wasm is the package's):
//   node tools/make-quickjs.js
const fs = require("fs"), path = require("path"), esbuild = require("esbuild");

const ROOT = path.join(__dirname, ".."), OUT = path.join(ROOT, "src", "js", "vendor");
const VARIANT = "@jitl/quickjs-wasmfile-release-sync";
const version = name => JSON.parse(fs.readFileSync(path.join(ROOT, "node_modules", ...name.split("/"), "package.json"), "utf8")).version;

fs.mkdirSync(OUT, { recursive: true });
const banner = "// QuickJS (Fabrice Bellard, Charlie Gordon - MIT) in WebAssembly through quickjs-emscripten-core " + version("quickjs-emscripten-core") +
  " + " + VARIANT + " " + version(VARIANT) + " (Jake Teton-Landis - MIT).\n// Generated by tools/make-quickjs.js - don't edit.";
const res = esbuild.buildSync({
  stdin: { contents: 'export { newQuickJSWASMModuleFromVariant, newVariant } from "quickjs-emscripten-core";\n' +
    'export { default as variant } from "' + VARIANT + '";\n', resolveDir: ROOT, sourcefile: "quickjs-entry.js" },
  bundle: true, format: "esm", platform: "browser", target: "es2020", minify: true, legalComments: "none", write: false,
  banner: { js: banner }, logLevel: "warning",
});
fs.writeFileSync(path.join(OUT, "quickjs.js"), res.outputFiles[0].text);
fs.copyFileSync(path.join(ROOT, "node_modules", ...VARIANT.split("/"), "dist", "emscripten-module.wasm"), path.join(OUT, "quickjs.wasm"));
for (const f of ["quickjs.js", "quickjs.wasm"]) console.log("src/js/vendor/" + f + ": " + fs.statSync(path.join(OUT, f)).size + " bytes");
