#!/usr/bin/env python3
"""Converts GNU Unifont (https://ftp.gnu.org/gnu/unifont/, the unifont_all-<version>.hex.gz file - or
unifont-<version>.hex.gz plus unifont_upper-<version>.hex.gz) into the glyph blocks the Unicode text
plane draws user text with (player names, room names, chat - any language, docs/DESIGN-8P.md 22):

  src/fonts/unifont/<block>.bin   one file per 256 code points that has glyphs (<block> = code point >> 8,
                                  3 or more lowercase hex digits, e.g. 04e.bin = U+4E00..U+4EFF):
                                    32 bytes  bitmap of the code points present (bit i & 7 of byte i >> 3)
                                    32 bytes  bitmap of the wide (16 x 16) ones
                                    then each present glyph in code point order: 16 bytes (8 x 16, one
                                    byte per row) or 32 bytes (16 x 16, two bytes per row, left first);
                                    bit 7 = leftmost pixel
  src/js/unidata.js               generated: the wide code point ranges (2 text cells) and the list of
                                  block files - unitext.js (and the server, for name lengths) use it

Only what the program can't draw better already: code points of code page 437 (the VGA ROM font) and of
src/js/glyphs.js (VGA-style letters from Uni2-VGA16) are left out (they are drawn - and measured - as one
8-pixel cell). The Basic Multilingual Plane without surrogates / private use / controls / variation
selectors, plus U+1F000..U+1FAFF (emoji and symbols) of the supplementary planes.

Usage: python3 -I tools/make-unifont.py <unifont hex.gz> [<more hex.gz> ...]"""
import gzip, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
OUT = os.path.join(ROOT, "src", "fonts", "unifont")
DATA = os.path.join(ROOT, "src", "js", "unidata.js")

def wanted(cp):
    if cp < 0x10000:
        return not (cp < 0x20 or 0x7F <= cp < 0xA0 or 0xD800 <= cp < 0xF900 or 0xFE00 <= cp <= 0xFE0F
                    or cp in (0xFEFF, 0xFFFE, 0xFFFF) or 0x200B <= cp <= 0x200F or 0x2028 <= cp <= 0x202E
                    or 0x2060 <= cp <= 0x206F)
    return 0x1F000 <= cp <= 0x1FAFF

# characters the VGA ROM font (CP437, with its pictures in the control range) or glyphs.js already draw
CONTROL = list("☺☻♥♦♣♠•◘○◙♂♀♪♫☼►◄↕‼¶§▬↨↑↓→←∟↔▲▼")
have = set(bytes([b]).decode("cp437") for b in range(0x20, 256)) | set(CONTROL)
gjs = open(os.path.join(ROOT, "src", "js", "glyphs.js"), encoding="utf-8").read()
m = re.search(r"const g = (\{.*?\});", gjs)
assert m, "glyphs.js: EXTRA_GLYPHS table not found"
have |= set(json.loads(m.group(1)).keys())
have_cp = set(ord(c) for c in have if len(c) == 1)

glyphs = {}
for src in sys.argv[1:]:
    with gzip.open(src, "rt", encoding="ascii") as f:
        for line in f:
            line = line.strip()
            if not line or ":" not in line: continue
            code, hexd = line.split(":", 1)
            cp = int(code, 16)
            if not wanted(cp) or cp in have_cp: continue
            if len(hexd) not in (32, 64): continue
            glyphs.setdefault(cp, bytes.fromhex(hexd))
if not glyphs:
    sys.exit(__doc__)

os.makedirs(OUT, exist_ok=True)
for f in os.listdir(OUT):
    if f.endswith(".bin"): os.remove(os.path.join(OUT, f))
blocks = sorted(set(cp >> 8 for cp in glyphs))
total = 0
for b in blocks:
    present, wide, data = bytearray(32), bytearray(32), bytearray()
    for i in range(256):
        g = glyphs.get((b << 8) | i)
        if g is None: continue
        present[i >> 3] |= 1 << (i & 7)
        if len(g) == 32: wide[i >> 3] |= 1 << (i & 7)
        data += g
    blob = bytes(present + wide + data)
    open(os.path.join(OUT, "%03x.bin" % b), "wb").write(blob)
    total += len(blob)

# wide ranges [first, last]
ranges = []
for cp in sorted(c for c, g in glyphs.items() if len(g) == 32):
    if ranges and ranges[-1][1] == cp - 1: ranges[-1][1] = cp
    else: ranges.append([cp, cp])
flat = []
for a, z in ranges: flat += [a, z]

js = '''// Generated by tools/make-unifont.py from GNU Unifont - do not edit.
// UNI_DATA.wide: code point ranges [first, last, first, last, ...] drawn 16 pixels wide (two text cells);
// UNI_DATA.blocks: the 256-code-point blocks with a glyph file (src/fonts/unifont/<block hex>.bin). Code
// points of code page 437 and glyphs.js are not in them (one 8-pixel cell, drawn from those fonts).
export const UNI_DATA = { wide: %s,
    blocks: %s };
''' % (json.dumps(flat, separators=(",", ":")), json.dumps(blocks, separators=(",", ":")))
open(DATA, "w", encoding="utf-8").write(js)
print("%d glyphs (%d wide) in %d block files, %d bytes; %d wide ranges; unidata.js %d bytes"
      % (len(glyphs), sum(1 for g in glyphs.values() if len(g) == 32), len(blocks), total, len(ranges), len(js)))
