#!/usr/bin/env python3
"""Regenerates the font of the graphics "modern" text screens (docs/GRAPHICS.md 3, src/js/gfx-text.js):
src/fonts/modern/NotoSansMono-Regular.woff2 + -Bold.woff2 (subsets of Noto Sans Mono, OFL-1.1: Latin,
Latin Extended-A / B / Additional, Greek, Cyrillic, punctuation, currency, letterlike, arrows, math,
technical, box drawing, blocks, geometric shapes, ...) and the list of the code points they cover, written
into src/js/gfx-text.js between the "font-ranges" markers (characters outside it are drawn from the
bitmap glyphs: the VGA ROM font, glyphs.js, GNU Unifont).

Needs fontTools + brotli (pip install fonttools brotli). Run from the repository:
  python3 -I tools/make-modern-font.py [Regular.ttf Bold.ttf]
Default sources: /usr/share/fonts/truetype/noto/NotoSansMono-{Regular,Bold}.ttf (Debian / Ubuntu
fonts-noto-mono)."""
import os
import re
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "fonts", "modern")
JS = os.path.join(ROOT, "src", "js", "gfx-text.js")
SRC = sys.argv[1:3] if len(sys.argv) >= 3 else [
    "/usr/share/fonts/truetype/noto/NotoSansMono-Regular.ttf",
    "/usr/share/fonts/truetype/noto/NotoSansMono-Bold.ttf",
]

RANGES = [
    (0x0020, 0x007E), (0x00A0, 0x00FF),          # Basic Latin, Latin-1
    (0x0100, 0x024F),                            # Latin Extended-A, -B
    (0x02B0, 0x02FF), (0x0300, 0x036F),          # spacing modifiers, combining marks
    (0x0370, 0x03FF),                            # Greek
    (0x0400, 0x052F),                            # Cyrillic + Supplement
    (0x1E00, 0x1EFF),                            # Latin Extended Additional
    (0x2000, 0x206F), (0x2070, 0x209F),          # punctuation, super- / subscripts
    (0x20A0, 0x20CF), (0x2100, 0x218F),          # currency, letterlike, number forms
    (0x2190, 0x21FF), (0x2200, 0x22FF),          # arrows, math operators
    (0x2300, 0x23FF),                            # technical
    (0x2500, 0x25FF),                            # box drawing, blocks, geometric shapes
    (0x2600, 0x27BF),                            # symbols, dingbats (what the font has)
    (0xFFFD, 0xFFFD),
]


def compact(cps):
    """sorted code points -> [[first, last], ...]"""
    out = []
    for c in sorted(cps):
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def main():
    os.makedirs(OUT, exist_ok=True)
    wanted = set()
    for a, b in RANGES:
        wanted.update(range(a, b + 1))
    covered = None
    for src in SRC:
        font = TTFont(src)
        have = set(font.getBestCmap()) & wanted
        covered = have if covered is None else covered & have
        opts = subset.Options()
        opts.flavor = "woff2"
        opts.hinting = False
        opts.desubroutinize = True
        opts.name_IDs = ["*"]
        opts.name_languages = ["*"]
        opts.notdef_outline = True
        sub = subset.Subsetter(opts)
        sub.populate(unicodes=sorted(have))
        sub.subset(font)
        name = os.path.splitext(os.path.basename(src))[0] + ".woff2"
        font.flavor = "woff2"
        font.save(os.path.join(OUT, name))
        print(name, os.path.getsize(os.path.join(OUT, name)), "bytes,", len(have), "characters")
    ranges = compact(covered)
    text = ",".join("0x%X,0x%X" % (a, b) for a, b in ranges)
    lines, line = [], ""
    for part in text.split(","):
        if len(line) + len(part) > 104:
            lines.append(line)
            line = ""
        line += part + ","
    lines.append(line)
    block = ("// <font-ranges> (generated by tools/make-modern-font.py: the code points the bundled font covers,\n"
             "// [first, last] pairs)\nconst FONT_RANGES = [\n" + "\n".join("  " + l for l in lines) + "\n];\n// </font-ranges>")
    js = open(JS, encoding="utf-8").read()
    js2, n = re.subn(r"// <font-ranges>.*?// </font-ranges>", lambda m: block, js, flags=re.S)
    if n != 1:
        sys.exit("gfx-text.js: no font-ranges block")
    open(JS, "w", encoding="utf-8").write(js2)
    print(len(covered), "code points in", len(ranges), "ranges")


main()
