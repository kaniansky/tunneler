#!/usr/bin/env python3
"""Generates src/js/glyphs.js: the CP437 byte -> Unicode table and VGA-style 8x16 glyphs for the
characters code page 437 lacks (Latin-1/Latin Extended-A/B for Slovak, Czech and other Latin languages,
Cyrillic for Ukrainian and Russian, Greek, common punctuation, currency and a few symbols), taken from the
Linux console font Uni2-VGA16 (same IBM VGA look as the ROM font). glyphs.js also gets unicodeGlyph(ch):
the glyph of any character from the ROM font (a pristine copy) or these extra glyphs - the Unicode text
layer (display.js, docs/DESIGN-8P.md 22) draws with it, independent of lang.js's font slots.
Usage: python3 tools/make-glyphs.py [/usr/share/consolefonts/Uni2-VGA16.psf.gz]"""
import gzip, struct, sys, json, base64, os

src = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/consolefonts/Uni2-VGA16.psf.gz"
d = gzip.open(src).read()
assert d[:2] == b"\x36\x04", "PSF1 font expected"
mode, h = d[2], d[3]
n = 512 if mode & 1 else 256
assert h == 16
glyphs = [d[4 + i * h:4 + (i + 1) * h] for i in range(n)]
tab, umap, i, g = d[4 + n * h:], {}, 0, 0
while g < n and i + 1 < len(tab):
    u = struct.unpack("<H", tab[i:i + 2])[0]; i += 2
    if u == 0xFFFF: g += 1; continue
    if u == 0xFFFE: continue
    umap.setdefault(u, g)

cp437 = [bytes([b]).decode("cp437") for b in range(256)]
have = set(cp437)
RANGES = [(0xA0, 0x100),      # Latin-1 (accented letters, punctuation)
          (0x100, 0x250),     # Latin Extended-A / B (Slovak, Czech, Polish, Romanian, ...)
          (0x370, 0x400),     # Greek
          (0x400, 0x460), (0x490, 0x492),   # Cyrillic (Ukrainian, Russian, ...)
          (0x1E00, 0x1F00),   # Latin Extended Additional (what the font has)
          (0x2000, 0x2070),   # general punctuation (dashes, quotes, bullet, ellipsis, ...)
          (0x20A0, 0x20C0),   # currency (euro, ...)
          (0x2100, 0x2150),   # letterlike (numero, trade mark)
          (0x2190, 0x2200),   # arrows
          (0x25A0, 0x2700)]   # shapes, misc symbols (what the font has)
wanted = [u for a, b in RANGES for u in range(a, b)]
# CP437 0x01..0x1F as the IBM font draws them (Python's cp437 codec maps them to control characters)
CONTROL = [""] + list("☺☻♥♦♣♠•◘○◙♂♀♪♫☼►◄↕‼¶§▬↨↑↓→←∟↔▲▼")
have |= set(CONTROL)
out = {}
for u in wanted:
    c = chr(u)
    if c in have or u not in umap: continue
    out[c] = base64.b64encode(glyphs[umap[u]]).decode()

js = '''"use strict";
// Generated by tools/make-glyphs.py - do not edit.
// CP437_CHARS: CP437 byte -> Unicode character. EXTRA_GLYPHS: 8x16 VGA-style glyphs (from the Linux
// console font Uni2-VGA16) for characters code page 437 lacks; lang.js loads a language's letters into
// unused font slots. unicodeGlyph(ch): the 16 rows of any character - CP437 from a pristine copy of the
// ROM font (vgafont.js, loaded before this file), else EXTRA_GLYPHS, else null - for the Unicode text
// layer (display.js), which shows every language at once.
(function (root) {
  root.CP437_CHARS = %s;
  const g = %s;
  const bin = s => { const b = typeof atob === "function" ? atob(s) : Buffer.from(s, "base64").toString("binary"); const a = new Uint8Array(16); for (let i = 0; i < 16; i++) a[i] = b.charCodeAt(i); return a; };
  root.EXTRA_GLYPHS = {};
  for (const c in g) root.EXTRA_GLYPHS[c] = bin(g[c]);
  const font = root.VGA_FONT ? root.VGA_FONT.slice() : null;
  const cp = new Map();
  for (let b = 0x20; b < 256; b++) if (b !== 0x7F) cp.set(root.CP437_CHARS[b], b);
  // the ROM font's pictures in the control range, under their usual Unicode names
  %s.forEach((c, i) => { if (c) cp.set(c, i); });
  root.unicodeGlyph = ch => {
    const b = cp.get(ch);
    if (b !== undefined && font) return font.subarray(b * 16, b * 16 + 16);
    return root.EXTRA_GLYPHS[ch] || null;
  };
})(typeof window !== "undefined" ? window : globalThis);
''' % (json.dumps("".join(cp437), ensure_ascii=False), json.dumps(out, ensure_ascii=False), json.dumps(CONTROL, ensure_ascii=False))
dst = os.path.join(os.path.dirname(__file__), "..", "src", "js", "glyphs.js")
open(dst, "w", encoding="utf-8").write(js)
print("wrote", dst, len(out), "glyphs")
