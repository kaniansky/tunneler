// t.rowH (the phone layout, dosui.js): each row's height in rows of the usual one - ch is the usual row,
// rh(r) row r's, Y(r) where it starts (fractions within the row: r + 0.5 = its middle)
// t.view = {rows, units, top} (the phone layout's scrolling): the first `rows` rows in a window `units` rows high
// from `top` (any fraction), the rest below it - clip = the window's height (drawn in two clipped passes)
function geometry(W, H, S, st) {
  const cols = S.c1 - S.c0, cw = W / cols, m = S.rowH, v = S.view;
  const n = v ? Math.min(v.rows, S.rows) : 0;
  let units = m ? m.reduce((a, b) => a + (b || 1), 0) : S.rows;
  if (v && m) units = v.units + m.slice(n).reduce((a, b) => a + (b || 1), 0);
  const ch = H / units, clip = v ? v.units * ch : 0, scroll = v ? v.top * ch : 0;
  // where each row starts: content rows by the running sum less the scroll, the rows below from the window's end
  const top = [];
  if (m) {
    let at = -scroll;
    for (let r = 0; r < S.rows; r++) {
      if (v && r === n) at = clip;
      top.push(at);
      at += (m[r] || 1) * ch;
    }
  }
  const rh = m ? r => (m[Math.max(0, Math.min(S.rows - 1, Math.floor(r)))] || 1) * ch : () => ch;
  const Y = m ? r => { const k = Math.max(0, Math.floor(r)); return k >= S.rows ? H : top[k] + (r - k) * rh(k); } : r => r * ch;
  const fs = Math.min(cw / ADVANCE, ch / 1.3), f = fs.toFixed(2) + "px " + STACK, fa = (fs * 1.3).toFixed(2) + "px " + STACK;
  return {
    W, H, cols, cw, ch, rh, rows: S.rows, c0: S.c0, fs, clip, scroll, nScroll: n, region: null,
    // (in a clipped pass, clipped(): only the window's rows, or only the ones below it)
    mine(r) { return !this.region || (this.region === "window" ? r < n : r >= n); },
    // (a text row worth drawing in this pass: its own region and, in the window, on the screen)
    seen(r) { return this.mine(r) && (this.region !== "window" || (Y(r) + rh(r) > 0 && Y(r) < clip)); }, base: ch / 2 + CAP * fs / 2, baseOf: r => rh(r) / 2 + CAP * fs / 2,
    X: c => (c - S.c0) * cw, Y,
    sx: c => Math.round((c - S.c0) * cw), sy: r => Math.round(Y(r)),
    lw: Math.max(1, Math.round(st.border * H / 720 * 2) / 2),
    fontR: f, fontB: "bold " + f, fontA: fa, fontBA: "bold " + fa,
  };
}
function layer(state, name, W, H, scale) {
  const w = Math.max(1, Math.ceil(W * (scale || 1))), h = Math.max(1, Math.ceil(H * (scale || 1)));
  let c = state[name];
  if (!c) c = state[name] = canvasOf(w, h);
  if (c.width !== w || c.height !== h) { c.width = w; c.height = h; }
  return c;
}
function prep(x) {
  x.setTransform(1, 0, 0, 1, 0, 0);
  x.globalAlpha = 1;
  x.globalCompositeOperation = "source-over";
  x.shadowColor = "transparent"; x.shadowBlur = 0; x.shadowOffsetX = 0; x.shadowOffsetY = 0;
  x.imageSmoothingEnabled = true;
  if ("imageSmoothingQuality" in x) x.imageSmoothingQuality = "high";
}

// background, panels (shadow, fill, frame, separators), background runs but the highlight, rule lines
function drawBase(ctx, S, st, g) {
  const { W, H, cw, ch, X, Y, sx, sy, lw } = g;
  prep(ctx);
  ctx.fillStyle = st.back;
  ctx.fillRect(0, 0, W, H);
  const R = ch * 0.12;                                // (clean: small corners, the same on panels and bars)
  for (const p of S.panels) {
    if (!g.mine(p.r)) continue;
    const x0 = X(p.c + 0.5), y0 = Y(p.r + 0.5), x1 = X(p.c2 + 0.5), y1 = Y(p.r2 + 0.5), col = st.fg[p.fg];
    ctx.beginPath();
    if (st.rounded) {                                 // (clean: a flat panel - no shadow, no tint)
      roundRect(ctx, x0, y0, x1 - x0, y1 - y0, R);
      ctx.fillStyle = PANEL;
      ctx.fill();
    } else {
      const rx = Math.round(x0), ry = Math.round(y0), rw = Math.round(x1 - x0), rh = Math.round(y1 - y0);
      ctx.fillStyle = "rgba(0,0,0,0.8)";
      ctx.fillRect(rx + Math.round(cw), ry + Math.round(ch * 0.5), rw, rh);
      ctx.fillStyle = "#000";
      ctx.fillRect(rx, ry, rw, rh);
      ctx.fillStyle = rgba(col, 0.09);
      ctx.fillRect(rx, ry, rw, rh);
    }
  }
  for (const p of S.panels) {
    if (!g.mine(p.r)) continue;
    const x0 = X(p.c + 0.5), y0 = Y(p.r + 0.5), x1 = X(p.c2 + 0.5), y1 = Y(p.r2 + 0.5), col = st.fg[p.fg];
    ctx.save();
    if (p.gaps.length) {                              // a title in the frame: the line stops around it
      ctx.beginPath();
      ctx.rect(0, 0, W, H);
      for (const [a, b, bot] of p.gaps) ctx.rect(X(a) - cw * 0.2, Y(bot ? p.r2 : p.r), X(b + 1) - X(a) + cw * 0.4, g.rh(bot ? p.r2 : p.r));
      ctx.clip("evenodd");
    }
    ctx.strokeStyle = st.rounded ? LINE : col;
    ctx.lineWidth = p.double && st.rounded ? lw * 2 : lw;
    ctx.beginPath();
    if (st.rounded) roundRect(ctx, x0, y0, x1 - x0, y1 - y0, R);
    else ctx.rect(Math.round(x0) + lw / 2, Math.round(y0) + lw / 2, Math.round(x1 - x0) - lw, Math.round(y1 - y0) - lw);
    ctx.stroke();
    if (p.double && !st.rounded) {
      const d = Math.max(3, Math.round(cw * 0.22));
      ctx.beginPath();
      ctx.rect(Math.round(x0) + d + lw / 2, Math.round(y0) + d + lw / 2, Math.round(x1 - x0) - 2 * d - lw, Math.round(y1 - y0) - 2 * d - lw);
      ctx.stroke();
    }
    ctx.restore();
    for (const y of p.seps) {
      const yy = Math.round(Y(y + 0.5)) + (lw % 2) / 2, a = x0 + (st.rounded ? cw * 0.6 : 0), b = x1 - (st.rounded ? cw * 0.6 : 0);
      ctx.lineWidth = lw;
      ctx.strokeStyle = st.rounded ? LINE : col;
      ctx.beginPath(); ctx.moveTo(a, yy); ctx.lineTo(b, yy); ctx.stroke();
    }
  }
  for (const q of S.runs) {
    if (q === S.hl || !g.mine(q.r)) continue;
    const x0 = X(q.c), w = X(q.c2 + 1) - x0;
    ctx.fillStyle = st.bg[q.bg];
    if (st.rounded) { const h = g.rh(q.r); ctx.beginPath(); roundRect(ctx, x0 + 1, Y(q.r) + h * 0.06, w - 2, h * 0.88, R); ctx.fill(); }
    else ctx.fillRect(sx(q.c), sy(q.r), sx(q.c2 + 1) - sx(q.c), sy(q.r + 1) - sy(q.r));
  }
  for (const q of S.rules) {
    if (!g.mine(q.r)) continue;
    const a = X(q.c), b = X(q.c2 + 1), y = Math.round(q.low ? Y(q.r + 1) - ch * 0.2 : Y(q.r + 0.5)) + (lw % 2) / 2, col = st.fg[q.fg];
    ctx.lineWidth = lw;
    ctx.strokeStyle = st.rounded ? LINE : col;
    ctx.beginPath(); ctx.moveTo(a, y); ctx.lineTo(b, y); ctx.stroke();
  }
}

// the text layer (transparent): runs of letters of one colour and weight as one string (the font's advance
// is the cell's width; otherwise letter by letter, centred), the rest per cell; under it the glow (retro:
// bright text; both: the big titles), drawn small and enlarged = blurred
function drawText(ctx, glow, S, t, st, g) {
  const { W, H, cw, ch, X, Y, sx, sy, lw, fs, base } = g, { rows, c0, c1, cp, box, used } = S;
  const vram = t.vram, blinkOn = t.blinkOn !== false;
  prep(ctx);
  ctx.clearRect(0, 0, W, H);
  ctx.textBaseline = "alphabetic";
  let adv = advances.get(g.fontR + fontState);
  if (adv === undefined) {
    ctx.font = g.fontR;
    adv = ctx.measureText("0000000000").width / 10;
    advances.set(g.fontR + fontState, adv);
  }
  const strings = Math.abs(adv - cw) < cw * 0.03;
  const ops = [];                                     // [kind, ...]: text runs and titles first (they glow)
  const inTitle = new Uint8Array(rows);
  for (const q of S.titles) inTitle[q.r] = 1;
  const hlRow = S.hl ? S.hl.r : -1;
  // (each op's row and columns: centred rows - t.centres, DosUI - are moved to the pixel in clean)
  const meta = [];
  let at = null;
  const add = op => { ops.push(op); meta.push({ r: at.r, c0: at.c, c1: at.c + 1 }); };
  for (let r = 0; r < rows; r++) {
    if (inTitle[r] || !g.seen(r)) continue;
    let run = null;
    for (let c = c0; c < c1; c++) {
      at = { r, c };
      const i = r * 80 + c, k = cp[i];
      const space = k === 0x20 || k === 0 || k === 0xA0;
      if (k === S.CONT || used[i] || space) { if (run && space && !used[i]) run.s += " "; else run = null; continue; }
      const attr = vram[r * 160 + c * 2 + 1], fg = attr & 15, bgc = (attr >> 4) & 7;
      if ((attr & 0x80) && !blinkOn || fg === bgc && !box[i]) { run = null; continue; }
      const color = bgc === 5 && r === hlRow && st.rounded ? ACCENT_TEXT : st.fg[fg];
      const x = X(c), y = Y(r), b = g.baseOf(r);
      if (box[i]) { run = null; add([2, box[i], x, y, color, g.rh(r)]); continue; }
      const blk = BLOCKS.get(k);
      if (blk) { run = null; add([3, blk, c, r, color]); continue; }
      const wide = t.uni && t.uni[i] && UniText.charCols(k) === 2;
      if (!covered(k) || wide) { run = null; add([4, k, x, y, color, g.rh(r), b]); continue; }
      const bold = r === hlRow && bgc === 5;
      const arrow = k >= 0x2190 && k <= 0x21FF, glows = st.glow && fg >= 9;
      if (arrow) {                                    // (the font's arrows are small: larger, on the text's middle)
        run = null;
        add([1, charOf(k), x + cw / 2, y + g.rh(r) / 2 + CAP * fs * 0.65 - fs * 0.02, bold ? g.fontBA : g.fontA, color, glows, "center"]);
        continue;
      }
      const font = bold ? g.fontB : g.fontR;
      if (strings && run && run.font === font && run.color === color) { run.s += charOf(k); meta[run.mi].c1 = c + 1; continue; }
      if (!strings) { run = null; add([1, charOf(k), x + cw / 2, y + b, font, color, glows, "center"]); continue; }
      run = { s: charOf(k), font, color, mi: meta.length };
      add([1, run, x, y + b, font, color, glows, "left"]);
    }
  }
  // clean: a centred row's text exactly in the middle of its columns (DosUI places it on whole cells: up to
  // half a cell off); retro stays on the DOS grid
  if (st.rounded && t.centres)
    for (const [r, a, b] of t.centres) {
      const idx = [];
      let lo = Infinity, hi = -Infinity;
      meta.forEach((m, k) => { if (m.r === r && m.c0 >= a && m.c1 <= b && ops[k][0] !== 3) { idx.push(k); lo = Math.min(lo, m.c0); hi = Math.max(hi, m.c1); } });
      if (!idx.length) continue;
      const dx = ((a + b) / 2 - (lo + hi) / 2) * cw;
      if (Math.abs(dx) > 0.01) for (const k of idx) ops[k][2] += dx;
    }
  // titles: larger, letter by letter on their cells' centre
  const titleOps = [];
  for (const q of S.titles) {
    if (!g.mine(q.r)) continue;
    const n = q.c2 - q.c + 1, mid = (X(q.c) + X(q.c2 + 1)) / 2;
    const s = Math.min(q.big ? 2 : 1.7, (g.cols * 0.8) / n), fT = fs * s, step = cw * s * 1.04;
    const font = "bold " + fT.toFixed(2) + "px " + STACK, y = Y(q.r) + g.rh(q.r) / 2 + CAP * fT / 2;
    const fill = st.fg[12];                           // (a solid colour: no gradient text)
    for (let c = q.c; c <= q.c2; c++) {
      const k = cp[q.r * 80 + c];
      if (k === 0x20 || k === 0) continue;
      const x = mid + (c - q.c - (n - 1) / 2) * step;
      if (covered(k)) titleOps.push([1, charOf(k), x, y, font, fill, st.glow, "center"]);
      else titleOps.push([4, k, x - cw / 2, Y(q.r), st.fg[12], g.rh(q.r), g.baseOf(q.r)]);
    }
  }
  const all = ops.concat(titleOps);
  let curFont = "", curFill = null, curAlign = "";
  const run = o => {
    switch (o[0]) {
      case 1:
        if (o[4] !== curFont) ctx.font = curFont = o[4];
        if (o[5] !== curFill) ctx.fillStyle = curFill = o[5];
        if (o[7] !== curAlign) ctx.textAlign = curAlign = o[7];
        ctx.fillText(typeof o[1] === "string" ? o[1] : o[1].s, o[2], o[3]);
        break;
      case 2: looseBox(ctx, o[1], o[2], o[3], cw, o[5] || ch, o[4], lw); curFill = null; break;
      case 3: {                                       // (in a taller row: the block at the usual height, centred)
        const r = o[3], h = g.rh(r), band = h > g.ch * 1.01 ? v => Math.round(g.Y(r) + (h - g.ch) / 2 + (v - r) * g.ch) : sy;
        block(ctx, o[1], o[2], o[3], sx, band, o[4], st.rounded, cp, rows, c0, c1); curFill = null; break;
      }
      case 4: bitmap(ctx, o[1], o[2], o[3], cw, o[5] || ch, fs, o[6] || base, o[4]); break;
    }
  };
  // the glow: what glows drawn first; around it (rectangles, merged, 4-pixel aligned) copied down to a half,
  // then a quarter (exact halvings = a box blur), the rest drawn, then the quarter enlarged behind it all
  const glows = o => o[0] === 1 && o[6];
  const lit = glow ? all.filter(glows) : [];
  for (const o of lit) run(o);
  const rects = [];
  if (lit.length) {
    const pad = Math.max(6, fs * 0.45);
    for (const o of lit) {
      const px = parseFloat(o[4].replace("bold ", "")), str = typeof o[1] === "string" ? o[1] : o[1].s;
      const w = o[7] === "left" ? str.length * cw : px * ADVANCE * str.length;
      const x0 = o[7] === "left" ? o[2] : o[2] - w / 2;
      const r = [Math.max(0, Math.floor((x0 - pad) / 4) * 4), Math.max(0, Math.floor((o[3] - px - pad) / 4) * 4)];
      r.push(Math.min(Math.ceil(W / 4) * 4, Math.ceil((x0 + w + pad) / 4) * 4), Math.min(Math.ceil(H / 4) * 4, Math.ceil((o[3] + px * 0.35 + pad) / 4) * 4));
      rects.push(r);
    }
    for (let merged = true; merged;) {                // (overlapping ones joined: nothing glows twice)
      merged = false;
      for (let i = 0; i < rects.length && !merged; i++)
        for (let j = i + 1; j < rects.length; j++) {
          const A = rects[i], B = rects[j];
          if (A[0] < B[2] && B[0] < A[2] && A[1] < B[3] && B[1] < A[3]) {
            rects[i] = [Math.min(A[0], B[0]), Math.min(A[1], B[1]), Math.max(A[2], B[2]), Math.max(A[3], B[3])];
            rects.splice(j, 1);
            merged = true;
            break;
          }
        }
    }
    const [ga, gb] = glow, xa = ga.getContext("2d"), xb = gb.getContext("2d");
    prep(xa); prep(xb);
    xa.clearRect(0, 0, ga.width, ga.height); xb.clearRect(0, 0, gb.width, gb.height);
    xa.imageSmoothingQuality = xb.imageSmoothingQuality = "low";
    for (const [x0, y0, x1, y1] of rects) xa.drawImage(ctx.canvas, x0, y0, x1 - x0, y1 - y0, x0 / 2, y0 / 2, (x1 - x0) / 2, (y1 - y0) / 2);
    for (const [x0, y0, x1, y1] of rects) xb.drawImage(ga, x0 / 2, y0 / 2, (x1 - x0) / 2, (y1 - y0) / 2, x0 / 4, y0 / 4, (x1 - x0) / 4, (y1 - y0) / 4);
  }
  for (const o of all) if (!lit.length || !glows(o)) run(o);
  if (rects.length) {
    ctx.globalCompositeOperation = "destination-over";
    ctx.globalAlpha = st.rounded ? 0.85 : 0.6;
    if ("imageSmoothingQuality" in ctx) ctx.imageSmoothingQuality = "low";
    for (const [x0, y0, x1, y1] of rects) ctx.drawImage(glow[1], x0 / 4, y0 / 4, (x1 - x0) / 4, (y1 - y0) / 4, x0, y0, x1 - x0, y1 - y0);
    ctx.globalAlpha = 1;
    ctx.globalCompositeOperation = "source-over";
  }
  // the text cursor (an empty input): an underline under its cell, blinking
  const cur = t.cursor;
  if (cur && blinkOn && cur.col >= c0 && cur.col < c1 && cur.row >= 0 && cur.row < rows && g.mine(cur.row)) {
    const x = X(cur.col) + cw * 0.12, w = cw * 0.76, y = Y(cur.row) + g.baseOf(cur.row) + fs * 0.14, h = Math.max(2, fs * 0.09);
    ctx.fillStyle = st.fg[15];
    if (st.rounded) { ctx.beginPath(); roundRect(ctx, x, y, w, h, h / 2); ctx.fill(); }
    else ctx.fillRect(Math.round(x), Math.round(y), Math.round(w), Math.round(h));
  }
}

// the highlight bar (clean: a solid bar in the one accent colour, small corners; retro: the DOS bar)
function drawBar(ctx, state, h, st, g) {
  const { cw } = g, ch = h.h || g.ch;                 // (the bar's row: taller ones on the phone layout)
  if (!st.rounded) { ctx.fillStyle = st.bg[5]; ctx.fillRect(Math.round(h.x), Math.round(h.y), Math.round(h.w), Math.round(ch)); return; }
  const ix = Math.min(cw * 0.35, h.w * 0.1);
  ctx.fillStyle = ACCENT;
  ctx.beginPath(); roundRect(ctx, h.x + ix, h.y + ch * 0.07, h.w - 2 * ix, ch * 0.86, g.ch * 0.12); ctx.fill();
}

// is t's content what the text layer shows?
function sameText(state, t, S, key) {
  if (state.textKey !== key || !state.vram || state.vram.length !== t.vram.length) return false;
  const a = state.vram, b = t.vram, n = Math.min(b.length, S.rows * 160);
  for (let i = 0; i < n; i++) if (a[i] !== b[i]) return false;
  const u = t.uni, v = state.uni;
  if (!!u !== !!v) return false;
  if (u) { if (u.length !== v.length) return false; for (let i = 0; i < u.length; i++) if (u[i] !== v[i]) return false; }
  const cur = t.cursor ? t.cursor.col + "," + t.cursor.row : "";
  if (cur !== state.cursor) return false;
  return !(S.blinks || cur) || state.blinkOn === (t.blinkOn !== false);
}
function keepText(state, t, key) {
  state.textKey = key;
  state.vram = Uint8Array.from(t.vram);
  state.uni = t.uni ? Uint32Array.from(t.uni) : null;
  state.cursor = t.cursor ? t.cursor.col + "," + t.cursor.row : "";
  state.blinkOn = t.blinkOn !== false;
}

function draw(ctx, W, H, t, opts) {
  loadFont();
  const style = STYLES[opts && opts.style] ? opts.style : "clean", st = STYLES[style], now = (opts && opts.now) || 0;
  // (the font still loading - from the cache after the first visit, a few ms: just the background for a
  // moment, so the screen doesn't appear in another font and change; again next frame)
  if (fontState === "loading" && now - fontSince < FONT_WAIT) {
    prep(ctx); ctx.fillStyle = st.back; ctx.fillRect(0, 0, W, H);
    return true;
  }
  const S = analyse(t), g = geometry(W, H, S, st);
  let state = states.get(ctx);
  if (!state) states.set(ctx, state = { hl: null, anim: null, sig: "" });
  const dims = [style, W, H, S.rows, S.c0, S.c1, S.rowH ? S.rowH.join(" ") : "", S.view ? S.view.top : ""].join(",");
  // the base layer
  const baseKey = dims + "|" + S.panels.map(p => [p.c, p.r, p.c2, p.r2, p.fg, p.double, p.gaps.join(" "), p.seps.join(" ")].join(",")).join(";")
    + "|" + S.runs.filter(q => q !== S.hl).map(q => [q.r, q.c, q.c2, q.bg].join(",")).join(";")
    + "|" + S.rules.map(q => [q.r, q.c, q.c2, q.fg, q.low].join(",")).join(";");
  const baseC = layer(state, "baseC", W, H);
  if (state.baseKey !== baseKey) { state.baseKey = baseKey; clipped(baseC.getContext("2d"), g, x => drawBase(x, S, st, g)); }
  // the text layer
  const textKey = dims + "|" + fontState + "|" + decStr;
  const textC = layer(state, "textC", W, H);
  let changed = state.shown !== baseKey;
  if (!sameText(state, t, S, textKey)) {
    changed = true;
    keepText(state, t, textKey);
    pending = false;
    const q4 = (W2, k) => Math.ceil(W2 / 4) * 4 * k;     // (the glow layers: a half and a quarter of a 4-aligned size)
    const glowL = [layer(state, "glowA", q4(W, 1), q4(H, 1), 0.5), layer(state, "glowB", q4(W, 1), q4(H, 1), 0.25)];
    clipped(textC.getContext("2d"), g, x => drawText(x, glowL, S, t, st, g));
    if (pending) state.textKey = null;
  }
  // the highlight bar: slides from where it was (on the same screen: the same panels)
  const sig = [style, W, H, S.rows, S.c0, S.c1, S.rowH ? S.rowH.join(" ") : ""].join(",") + "|" + S.panels.map(p => p.c + "," + p.r + "," + p.c2 + "," + p.r2).join(";");
  const inWin = S.hl && S.hl.r < g.nScroll, sc = inWin ? g.scroll : 0;   // (the bar in content coordinates: it scrolls with it)
  const target = S.hl ? { x: g.X(S.hl.c), y: g.Y(S.hl.r) + sc, w: g.X(S.hl.c2 + 1) - g.X(S.hl.c), h: g.rh(S.hl.r) } : null;
  const same = (a, b) => a.x === b.x && a.y === b.y && a.w === b.w && a.h === b.h;
  let animating = false;
  // (it slides only up and down within one box - the same column and width; to another box it jumps)
  const inBox = (a, b) => Math.abs(a.x - b.x) < 1 && Math.abs(a.w - b.w) < 1;
  if (!target || sig !== state.sig || !state.hl) { state.anim = null; state.hl = target; }
  else if (!same(state.anim ? state.anim.to : state.hl, target)) {
    if (inBox(state.anim ? state.anim.to : state.hl, target)) state.anim = { from: { ...state.hl }, to: target, t0: now };
    else { state.anim = null; state.hl = target; }
  }
  state.sig = sig;
  if (state.anim) {
    const a = state.anim, k = ease(Math.min(1, Math.max(0, (now - a.t0) / SLIDE_MS)));
    state.hl = { x: a.from.x + (a.to.x - a.from.x) * k, y: a.from.y + (a.to.y - a.from.y) * k, w: a.from.w + (a.to.w - a.from.w) * k,
      h: (a.from.h || g.ch) + ((a.to.h || g.ch) - (a.from.h || g.ch)) * k };
    if (k >= 1) { state.anim = null; state.hl = target; } else animating = true;
  }
  // (nothing changed: the output still shows it)
  const cv = ctx.canvas, bar = state.hl ? [state.hl.x, state.hl.y - sc, state.hl.w, state.hl.h].join(",") : "";
  if (t.pic !== state.pic) { state.pic = t.pic; changed = true; }
  if (!changed && !animating && state.shownBar === bar && cv && cv.width === W && cv.height === H) return false;
  state.shown = baseKey; state.shownBar = bar;
  prep(ctx);
  ctx.drawImage(baseC, 0, 0);
  if (state.hl) {
    const ix = Math.min(g.cw * 0.35, target.w * 0.1);
    state.barW = target.w - 2 * ix;
    const hb = Object.assign({}, state.hl, { y: state.hl.y - sc });
    if (inWin) { ctx.save(); ctx.beginPath(); ctx.rect(0, 0, W, g.clip); ctx.clip(); drawBar(ctx, state, hb, st, g); ctx.restore(); }
    else drawBar(ctx, state, hb, st, g);
  }
  ctx.drawImage(textC, 0, 0);
  if (t.pic) drawPic(ctx, t.pic, g);
  return animating;
}

// a DOS screen's picture (t.pic: a map's preview, DosUI spec.pic) in its block of cells: square, centred, crisp pixels
// (the phone layout's scrolling window clips it)
const picCanvases = new WeakMap();
function drawPic(ctx, pic, g) {
  let c = picCanvases.get(pic.rgba);
  if (!c) {
    c = canvasOf(pic.w, pic.h);
    const x = c.getContext("2d");
    if (!x || !x.putImageData || typeof ImageData === "undefined") return;
    x.putImageData(new ImageData(pic.rgba, pic.w, pic.h), 0, 0);
    picCanvases.set(pic.rgba, c);
  }
  const x0 = g.X(pic.col), x1 = g.X(pic.col + pic.cols), y0 = g.Y(pic.row), y1 = g.Y(pic.row + pic.rows);
  const k = Math.min((x1 - x0) / pic.w, (y1 - y0) / pic.h), w = pic.w * k, h = pic.h * k;
  ctx.save();
  if (g.clip && pic.row < g.nScroll) { ctx.beginPath(); ctx.rect(0, 0, g.W, g.clip); ctx.clip(); }
  ctx.imageSmoothingEnabled = false;
  ctx.drawImage(c, Math.round(x0 + (x1 - x0 - w) / 2), Math.round(y0 + (y1 - y0 - h) / 2), Math.round(w), Math.round(h));
  ctx.restore();
}

// draw(ctx) once - or, with a scrolling window (g.clip), twice: clipped to the window, then to the rest
function clipped(ctx, g, draw) {
  if (!g.clip) { draw(ctx); return; }
  for (const [a, b, region] of [[0, g.clip, "window"], [g.clip, g.H, "below"]]) {
    ctx.save();
    ctx.beginPath(); ctx.rect(0, a, g.W, b - a); ctx.clip();
    g.region = region;
    draw(ctx);
    ctx.restore();
  }
  g.region = null;
}

// a loose box-drawing piece: lines from the cell's centre to the edges it connects
function looseBox(ctx, k, x, y, cw, ch, color, lw) {
  const cx = Math.round(x + cw / 2) + (lw % 2) / 2, cy = Math.round(y + ch / 2) + (lw % 2) / 2;
  const dx = Math.max(2, cw * 0.18), dy = Math.max(2, ch * 0.09);
  ctx.strokeStyle = color;
  ctx.lineWidth = lw;
  ctx.beginPath();
  const seg = (n, x0, y0, x1, y1, ox, oy) => {
    if (!n) return;
    if (n === 1) { ctx.moveTo(x0, y0); ctx.lineTo(x1, y1); return; }
    ctx.moveTo(x0 - ox, y0 - oy); ctx.lineTo(x1 - ox, y1 - oy);
    ctx.moveTo(x0 + ox, y0 + oy); ctx.lineTo(x1 + ox, y1 + oy);
  };
  seg(U(k), cx, cy, cx, y, dx, 0);
  seg(D(k), cx, cy, cx, y + ch, dx, 0);
  seg(L(k), cx, cy, x, cy, 0, dy);
  seg(R(k), cx, cy, x + cw, cy, 0, dy);
  ctx.stroke();
}

// a shade / block character; clean: a full block's vertical run (e.g. a scroll bar's thumb) rounded
function block(ctx, b, c, r, sx, sy, color, rounded, cp, rows, c0, c1) {
  const x0 = sx(c + b[0]), x1 = sx(c + b[2]), y0 = sy(r + b[1]), y1 = sy(r + b[3]);
  ctx.globalAlpha = b[4];
  ctx.fillStyle = color;
  if (rounded && b[0] === 0 && b[2] === 1 && b[1] === 0 && b[3] === 1) {
    const k = cp[r * 80 + c], up = r > 0 && cp[(r - 1) * 80 + c] === k, dn = r + 1 < rows && cp[(r + 1) * 80 + c] === k;
    const w = x1 - x0, inset = w * (b[4] < 1 ? 0.38 : 0.22), rad = (w - 2 * inset) / 2;
    ctx.beginPath();
    // (a run of them as one rounded bar: only its ends rounded)
    const top = up ? y0 : y0 + inset * 0.5, bot = dn ? y1 : y1 - inset * 0.5;
    if (up && dn) ctx.rect(x0 + inset, top, w - 2 * inset, bot - top);
    else if (!up && !dn) roundRect(ctx, x0 + inset, top, w - 2 * inset, bot - top, rad);
    else {
      roundRect(ctx, x0 + inset, top, w - 2 * inset, bot - top, rad);
      ctx.rect(x0 + inset, up ? top : (top + bot) / 2, w - 2 * inset, (bot - top) / 2);
    }
    ctx.fill("nonzero");
  } else ctx.fillRect(x0, y0, x1 - x0, y1 - y0);
  ctx.globalAlpha = 1;
}

// a character the font lacks: its bitmap glyph, enlarged smoothly, on the font's baseline
function bitmap(ctx, k, x, y, cw, ch, fs, base, color) {
  const m = tintOf(k, color);
  if (!m) return;
  const h = Math.min(ch, fs * 1.18), s = h / ch;
  const w = (m.wide ? cw * 2 * 16 / 18 : cw * 8 / 9) * s;
  const cx = x + (m.wide ? cw : cw / 2);
  const top = y + base - h * 12 / 16;
  ctx.drawImage(m.c, cx - w / 2, top, w, h);
}

