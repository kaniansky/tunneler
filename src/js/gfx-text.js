function loadFont() {
  if (fontState !== "none") return;
  fontState = "loading";
  fontSince = root.performance ? root.performance.now() : 0;
  const doc = root.document, FF = root.FontFace;
  if (!doc || !doc.fonts || !FF) { fontState = "failed"; return; }
  const faces = [["NotoSansMono-Regular.woff2", "400"], ["NotoSansMono-Bold.woff2", "700"]].map(([f, w]) => {
    const face = new FF(FAMILY, "url(" + FONT_BASE + f + ")", { weight: w, style: "normal", display: "block" });
    doc.fonts.add(face);
    return face.load();
  });
  Promise.all(faces).then(() => { fontState = "ready"; }, e => {
    fontState = "failed";
    if (root.console) console.warn("gfx-text: font", e);
  }).then(() => { Gfx.refresh(); if (fontDone && fontDone.resolve) fontDone.resolve(); });
}

