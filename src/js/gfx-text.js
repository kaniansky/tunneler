// ------------------------------------------------------------ bitmap glyphs (characters the font lacks)
// a glyph's mask enlarged twice by Scale2x (EPX: diagonals smoothed, no blur), then drawn scaled with
// smoothing, tinted per colour; cached
const masks = new Map(), tinted = new Map();
function canvasOf(w, h) {
  // (a page's canvas where there is a page: composing OffscreenCanvas layers into one is slow in Chrome)
  if (!root.document || !root.document.createElement) return new root.OffscreenCanvas(w, h);
  const c = root.document.createElement("canvas"); c.width = w; c.height = h; return c;
}
function scale2x(src, w, h) {
  const out = new Uint8Array(w * h * 4), at = (x, y) => x < 0 || y < 0 || x >= w || y >= h ? 0 : src[y * w + x];
  for (let y = 0; y < h; y++)
    for (let x = 0; x < w; x++) {
      const P = at(x, y), A = at(x, y - 1), B = at(x + 1, y), C = at(x - 1, y), Dd = at(x, y + 1);
      const o = (y * 2) * (w * 2) + x * 2;
      out[o] = C === A && C !== Dd && A !== B ? A : P;
      out[o + 1] = A === B && A !== C && B !== Dd ? B : P;
      out[o + w * 2] = Dd === C && Dd !== B && C !== A ? C : P;
      out[o + w * 2 + 1] = B === Dd && B !== A && Dd !== C ? Dd : P;
    }
  return out;
}
function maskOf(cp) {
  let m = masks.get(cp);
  if (m !== undefined) return m;
  const Dsp = Display, g = Dsp && Dsp.glyphOf ? Dsp.glyphOf(cp) : null;
  if (!g || !g.rows) return null;                     // (a Unifont block still loading: drawn when it arrives)
  const w = g.wide ? 16 : 8;
  let px = new Uint8Array(w * 16);
  for (let y = 0; y < 16; y++)
    for (let x = 0; x < w; x++) {
      const bits = g.wide ? (g.rows[y * 2] << 8) | g.rows[y * 2 + 1] : g.rows[y];
      px[y * w + x] = (bits >> (w - 1 - x)) & 1;
    }
  px = scale2x(scale2x(px, w, 16), w * 2, 32);
  const W4 = w * 4, H4 = 64, c = canvasOf(W4, H4), x = c.getContext("2d"), img = x.createImageData(W4, H4);
  for (let i = 0; i < W4 * H4; i++) { img.data[i * 4] = img.data[i * 4 + 1] = img.data[i * 4 + 2] = 255; img.data[i * 4 + 3] = px[i] ? 255 : 0; }
  x.putImageData(img, 0, 0);
  m = { c, wide: !!g.wide };
  if (masks.size > 600) masks.clear();
  masks.set(cp, m);
  return m;
}
let pending = false, listening = false;               // a glyph still loading: the text layer drawn again once it is there
function tintOf(cp, color) {
  const key = cp + color;
  let t = tinted.get(key);
  if (t) return t;
  const m = maskOf(cp);
  if (!m) {
    pending = true;
    if (!listening) {
      listening = true;
      UniFont.onLoad(() => Gfx.refresh());
    }
    return null;
  }
  const c = canvasOf(m.c.width, m.c.height), x = c.getContext("2d");
  x.drawImage(m.c, 0, 0);
  x.globalCompositeOperation = "source-in";
  x.fillStyle = color;
  x.fillRect(0, 0, c.width, c.height);
  t = { c, wide: m.wide };
  if (tinted.size > 800) tinted.clear();
  tinted.set(key, t);
  return t;
}

// ------------------------------------------------------------ shapes
function roundRect(ctx, x, y, w, h, r) {
  r = Math.max(0, Math.min(r, w / 2, h / 2));
  ctx.moveTo(x + r, y);
  ctx.lineTo(x + w - r, y); ctx.arcTo(x + w, y, x + w, y + r, r);
  ctx.lineTo(x + w, y + h - r); ctx.arcTo(x + w, y + h, x + w - r, y + h, r);
  ctx.lineTo(x + r, y + h); ctx.arcTo(x, y + h, x, y + h - r, r);
  ctx.lineTo(x, y + r); ctx.arcTo(x, y, x + r, y, r);
  ctx.closePath();
}

// ------------------------------------------------------------ the screen as data
// Panels (closed frames: a top-left corner, its top-right on the same row, the bottom corners below - the
// top edge may carry a title), their separators (├───┤ rows), background runs, rule lines, and which
// cells are left as text / loose box pieces. Pure (no canvas): also used by test/gfx-text-check.js.
function analyse(t) {
  const rows = t.rows, c0 = t.c0 || 0, c1 = t.c1 || 80, vram = t.vram, uni = t.uni;
  const CONT = UniText.CONT;
  const dec = decodeTable(), n = rows * 80;
  const cp = new Uint32Array(n), box = new Uint8Array(n), used = new Uint8Array(n);
  for (let r = 0; r < rows; r++)
    for (let c = c0; c < c1; c++) {
      const i = r * 80 + c, u = uni ? uni[i] : 0;
      cp[i] = u === CONT ? CONT : u || dec[vram[r * 160 + c * 2]];
      box[i] = u ? 0 : BOX.get(cp[i]) || 0;
    }
  const at = (r, c) => r < 0 || r >= rows || c < c0 || c >= c1 ? 0 : box[r * 80 + c];
  const panels = [];
  for (let r = 0; r < rows; r++)
    for (let c = c0; c < c1; c++) {
      if (!isTL(box[r * 80 + c]) || used[r * 80 + c]) continue;
      let c2 = -1, r2 = -1;
      for (let x = c + 1; x < c1; x++) { const k = at(r, x); if (isTR(k)) { c2 = x; break; } if (isTL(k) || isV(k) && !isH(k)) break; }
      if (c2 < 0) continue;
      for (let y = r + 1; y < rows; y++) { const k = at(y, c); if (isBL(k)) { r2 = y; break; } if (!isV(k)) break; }
      if (r2 < 0 || !isBR(at(r2, c2))) continue;
      let ok = true;
      for (let y = r + 1; y < r2 && ok; y++) ok = isV(at(y, c2));
      if (!ok) continue;
      const a = vram[r * 160 + c * 2 + 1];
      const p = { c, r, c2, r2, fg: a & 15, double: R(box[r * 80 + c]) === 2, gaps: [], seps: [] };
      // the edges: box pieces consumed, other characters (a title) cut a gap into the line
      for (const y of [r, r2]) {
        let g = null;
        for (let x = c; x <= c2; x++) {
          const i = y * 80 + x;
          if (box[i] && (isH(box[i]) || x === c || x === c2)) { used[i] = 1; g = null; }
          else if (y === r) { if (g) g[1] = x; else p.gaps.push(g = [x, x]); }
          else if (!g) { p.gaps.push(g = [x, x, 1]); } else g[1] = x;
        }
      }
      for (let y = r + 1; y < r2; y++) {
        used[y * 80 + c] = used[y * 80 + c2] = 1;
        // a separator: ├ ... ┤ with horizontal lines between
        if (R(box[y * 80 + c]) && L(box[y * 80 + c2])) {
          let all = true;
          for (let x = c + 1; x < c2 && all; x++) all = isH(box[y * 80 + x]);
          if (all) { p.seps.push(y); for (let x = c + 1; x < c2; x++) used[y * 80 + x] = 1; }
        }
      }
      panels.push(p);
    }
  // background runs (per row; cells whose background isn't black)
  const runs = [];
  for (let r = 0; r < rows; r++) {
    let run = null;
    for (let c = c0; c < c1; c++) {
      const bg = (vram[r * 160 + c * 2 + 1] >> 4) & 7;
      if (bg && run && run.bg === bg && run.c2 === c - 1) run.c2 = c;
      else if (bg) runs.push(run = { r, c, c2: c, bg });
      else run = null;
    }
  }
  // the highlight bar: the widest magenta run
  let hl = null;
  for (const q of runs) if (q.bg === 5 && (!hl || q.c2 - q.c > hl.c2 - hl.c)) hl = q;
  // rule lines: 8+ underscores / hyphens in a row
  const rules = [];
  for (let r = 0; r < rows; r++) {
    let s = -1;
    for (let c = c0; c <= c1; c++) {
      const ch = c < c1 ? cp[r * 80 + c] : 0;
      const same = s >= 0 && ch === cp[r * 80 + s] && vram[r * 160 + c * 2 + 1] === vram[r * 160 + s * 2 + 1];
      if (same) continue;
      if (s >= 0 && c - s >= 8) {
        rules.push({ r, c: s, c2: c - 1, fg: vram[r * 160 + s * 2 + 1] & 15, low: cp[r * 80 + s] === 0x5F });
        for (let x = s; x < c; x++) used[r * 80 + x] = 1;
      }
      s = ch === 0x5F || ch === 0x2D ? c : -1;
    }
  }
  // titles: a row of bright red text with blank rows above and below (drawn larger) - on a whole screen (20+ rows, not
  // a status line) or the phone layout's (t.view: as short as its content - owner, 2026-10-27: a short phone screen's
  // title, "Controls", stayed small while "MAP" was large)
  const titles = [];
  const blank = (r, a, b) => {
    if (r < 0 || r >= rows) return true;
    for (let c = Math.max(c0, a); c <= Math.min(c1 - 1, b); c++) {
      const ch = cp[r * 80 + c], at2 = vram[r * 160 + c * 2 + 1];
      if (!(ch === 0x20 || ch === 0) || (at2 >> 4) & 7) return false;
    }
    return true;
  };
  // (never a menu's info rows: a one-line red message under a menu - "Press again to delete it." - isn't a title)
  const infoRow = new Set(Array.isArray(t.infoRows) ? t.infoRows : []);
  for (let r = 0; r < rows && (rows >= 20 || t.view); r++) {
    if (infoRow.has(r)) continue;
    let a = -1, b = -1, ok = true;
    for (let c = c0; c < c1; c++) {
      const i = r * 80 + c, ch = cp[i];
      if (ch === 0x20 || ch === 0) continue;
      if ((vram[r * 160 + c * 2 + 1] & 0x7F) !== 0x0C || used[i] || box[i]) { ok = false; break; }
      if (a < 0) a = c;
      b = c;
    }
    if (ok && a >= 0 && b - a < 30 && blank(r - 1, a - 2, b + 2) && blank(r + 1, a - 2, b + 2)) titles.push({ r, c: a, c2: b, big: blank(r - 2, a - 2, b + 2) && blank(r + 2, a - 2, b + 2) });
  }
  let blinks = false;
  for (let r = 0; r < rows && !blinks; r++) for (let c = c0; c < c1; c++) if (vram[r * 160 + c * 2 + 1] & 0x80) { blinks = true; break; }
  return { rows, c0, c1, cp, box, used, panels, runs, hl, rules, titles, blinks, CONT, rowH: Array.isArray(t.rowH) ? t.rowH : null, view: t.view || null };
}

