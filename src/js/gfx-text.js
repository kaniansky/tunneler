const ALL256 = Array.from({ length: 256 }, (_, i) => String.fromCharCode(i)).join("");
let decStr = null;
const DEC = new Uint32Array(256);
function decodeTable() {
  const L = Lang;
  const s = L && L.decode ? L.decode(ALL256) : ALL256;
  if (s !== decStr) {
    decStr = s;
    let i = 0;
    for (const ch of s) { if (i < 256) DEC[i++] = ch.codePointAt(0); }
    for (; i < 256; i++) DEC[i] = i;
  }
  return DEC;
}
